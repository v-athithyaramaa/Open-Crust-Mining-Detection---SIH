    def _generate_compliance_charts(self, data: Dict) -> List[Dict]:
        """Generate charts for compliance reports"""
        charts = []
        
        try:
            # Compliance score gauge
            score = data['overall_compliance_score']
            
            fig, ax = plt.subplots(figsize=(8, 6))
            colors = ['#dc3545', '#ffc107', '#28a745']
            wedges = [33.33, 33.33, 33.34]
            
            # Create gauge chart
            theta = np.linspace(0, np.pi, 100)
            r = 1
            
            # Draw gauge sections
            for i, (color, wedge) in enumerate(zip(colors, wedges)):
                start_angle = i * np.pi / 3
                end_angle = (i + 1) * np.pi / 3
                theta_section = np.linspace(start_angle, end_angle, int(wedge))
                x = r * np.cos(theta_section)
                y = r * np.sin(theta_section)
                ax.fill_between(theta_section, 0, 1, color=color, alpha=0.7)
            
            # Add score indicator
            score_angle = np.pi * (1 - score / 100)
            ax.plot([score_angle, score_angle], [0, 1], 'k-', linewidth=4)
            
            ax.set_xlim(-1.2, 1.2)
            ax.set_ylim(-0.2, 1.2)
            ax.set_aspect('equal')
            ax.axis('off')
            ax.text(0, -0.1, f'{score}%', ha='center', va='center', fontsize=20, fontweight='bold')
            ax.set_title('Compliance Score', fontsize=16, fontweight='bold')
            
            buffer = io.BytesIO()
            plt.savefig(buffer, format='png', bbox_inches='tight', dpi=150)
            buffer.seek(0)
            chart_b64 = base64.b64encode(buffer.getvalue()).decode()
            plt.close()
            
            charts.append({
                'title': 'Compliance Score',
                'type': 'gauge',
                'data': chart_b64,
                'format': 'png'
            })
            
        except Exception as e:
            logger.error(f"Error generating compliance charts: {e}")
        
        return charts
    
