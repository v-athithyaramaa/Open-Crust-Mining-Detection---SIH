    def _assess_compliance_risk(self, data: Dict) -> Dict:
        """Assess compliance risk level"""
        score = data['overall_compliance_score']
        violations = data['total_violations']
        
        if score < 50 or violations > 10:
            risk_level = 'HIGH'
            risk_color = '#dc3545'
        elif score < 75 or violations > 5:
            risk_level = 'MEDIUM'
            risk_color = '#ffc107'
        else:
            risk_level = 'LOW'
            risk_color = '#28a745'
        
        return {
            'level': risk_level,
            'color': risk_color,
            'score': score,
            'recommendation': f"Risk level is {risk_level}. {'Immediate action required.' if risk_level == 'HIGH' else 'Continue monitoring.' if risk_level == 'LOW' else 'Increased vigilance recommended.'}"
        }
    
    def _get_score_class(self, score: int) -> str:
        """Get CSS class based on compliance score"""
        if score >= 80:
            return 'high'
        elif score >= 60:
            return 'medium'
        else:
            return 'low'
    
