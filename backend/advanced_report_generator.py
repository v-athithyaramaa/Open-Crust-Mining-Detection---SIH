    def generate_violation_report(self, violation_data: Dict, 
                                config: ReportConfig) -> Dict:
        """
        Generate comprehensive violation report
        
        Args:
            violation_data: Dictionary containing violation information
            config: Report configuration settings
            
        Returns:
            Generated report data and metadata
        """
        try:
            logger.info(f"📋 Generating {config.format} violation report...")
            
            # Prepare report data
            report_data = self._prepare_violation_data(violation_data)
            
            # Generate different formats based on config
            if config.format == 'html':
                report_content = self._generate_html_report(report_data, 'violation')
            elif config.format == 'pdf':
                report_content = self._generate_pdf_report(report_data, 'violation')
            elif config.format == 'json':
                report_content = json.dumps(report_data, indent=2)
            elif config.format == 'excel':
                report_content = self._generate_excel_report(report_data, 'violation')
            else:
                raise ValueError(f"Unsupported format: {config.format}")
            
            # Add charts if requested
            charts = []
            if config.include_charts:
                charts = self._generate_violation_charts(report_data)
            
            # Generate insights and recommendations
            insights = self._generate_ai_insights(report_data, 'violation')
            recommendations = self._generate_recommendations(report_data, config.recipient_level)
            
            return {
                'report_id': report_data['report_id'],
                'format': config.format,
                'content': report_content,
                'charts': charts,
                'insights': insights,
                'recommendations': recommendations,
                'metadata': {
                    'generation_time': datetime.now().isoformat(),
                    'data_sources': ['satellite_imagery', 'ai_detection', 'field_inspection'],
                    'confidence_score': report_data.get('confidence_score', 0.85),
                    'classification': config.classification,
                    'recipient_level': config.recipient_level
                }
            }
            
        except Exception as e:
            logger.error(f"❌ Error generating violation report: {e}")
            return {'error': str(e)}
    
